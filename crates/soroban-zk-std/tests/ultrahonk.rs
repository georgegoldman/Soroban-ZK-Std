//! Positive and negative vectors for the UltraHonk verification core.
//!
//! The KZG vectors are genuine: the SRS, commitments and openings are built
//! with arkworks (the repository's trusted BN254 reference), so the positive
//! cases exercise a real pairing equation rather than a trivially satisfied
//! identity. The end-to-end vectors build an honest Sumcheck chain plus
//! consistent openings for the transcript-derived evaluation point.

use ark_bn254::{Fr as ArkFr, G1Projective as ArkG1, G2Projective as ArkG2};
use ark_ec::{CurveGroup, PrimeGroup};
use ark_ff::{BigInteger, PrimeField, Zero};
use ethnum::u256;
use soroban_sdk::Env;
use soroban_zk_core::sumcheck::{MultilinearPolynomial, RoundPolynomial};
use soroban_zk_core::{Bn254, G1Affine, ZkError};
use soroban_zk_std::pairing::G2Affine;
use soroban_zk_std::ultrahonk::{
    derive_honk_challenges, honk_public_inputs_digest, honk_vk_digest, reduce_opening_claims,
    verify_kzg_openings, verify_ultrahonk, ChallengeHash, HonkProof, HonkTranscript,
    HonkVerifyingKey, OpeningClaim, G1_IDENTITY, HONK_FORMAT_VERSION, MAX_LOG_N,
    NUM_SUMCHECK_EVALUATIONS, NUM_UNSHIFTED_EVALUATIONS, SUMCHECK_TERMS,
};

const LOG_N: u32 = 2;

// ── arkworks <-> crate conversions ──────────────────────────────────────────

fn field_to_u256<F: PrimeField>(value: F) -> u256 {
    let bytes = value.into_bigint().to_bytes_be();
    let mut buffer = [0u8; 32];
    buffer[32 - bytes.len()..].copy_from_slice(&bytes);
    u256::from_be_bytes(buffer)
}

fn g1_of(point: ArkG1) -> G1Affine {
    let affine = point.into_affine();
    G1Affine {
        x: field_to_u256(affine.x),
        y: field_to_u256(affine.y),
    }
}

fn g2_of(point: ArkG2) -> G2Affine {
    let affine = point.into_affine();
    G2Affine {
        x: (field_to_u256(affine.x.c0), field_to_u256(affine.x.c1)),
        y: (field_to_u256(affine.y.c0), field_to_u256(affine.y.c1)),
    }
}

fn tau() -> ArkFr {
    ArkFr::from(42u64)
}

fn g1_generator() -> G1Affine {
    g1_of(ArkG1::generator())
}

/// Commitment to `coeffs` under the SRS generated by `tau()`.
fn commit(coeffs: &[ArkFr]) -> G1Affine {
    let mut acc = ArkG1::zero();
    let mut power = ArkFr::from(1u64);
    for &coefficient in coeffs {
        acc += ArkG1::generator() * (coefficient * power);
        power *= tau();
    }
    g1_of(acc)
}

/// Commitment to `f(X) = constant + X`, used by the end-to-end fixture.
fn commitment_for_linear(constant: u64) -> G1Affine {
    g1_of(ArkG1::generator() * (ArkFr::from(constant) + tau()))
}

fn srs_g2() -> G2Affine {
    g2_of(ArkG2::generator() * tau())
}

// ── fixtures ───────────────────────────────────────────────────────────────

fn synthetic_vk(log_n: u32, num_public_inputs: u32) -> HonkVerifyingKey {
    let one = g1_generator();
    HonkVerifyingKey {
        version: HONK_FORMAT_VERSION,
        log_n,
        num_public_inputs,
        selectors: [one; 8],
        sigmas: [one; 4],
        ids: [one; 4],
        tables: [one; 4],
        lagrange_first: one,
        lagrange_last: one,
        srs_g2: srs_g2(),
    }
}

/// Honest degree-1 Sumcheck rounds for `evaluations`, absorbing each round into
/// `transcript` exactly like the verifier does.
fn honest_rounds(
    env: &Env,
    evaluations: &[u256],
    transcript: &mut HonkTranscript,
) -> (Vec<RoundPolynomial<SUMCHECK_TERMS>>, Vec<u256>) {
    let mut table = evaluations.to_vec();
    let mut rounds = Vec::new();
    let mut challenges = Vec::new();

    while table.len() > 1 {
        let half = table.len() / 2;
        let mut at_zero = u256::from(0u8);
        let mut at_one = u256::from(0u8);
        for j in 0..half {
            at_zero = Bn254::add(at_zero, table[j]);
            at_one = Bn254::add(at_one, table[j + half]);
        }
        let round = RoundPolynomial::<SUMCHECK_TERMS>::from_coefficients(&[
            at_zero,
            Bn254::sub(at_one, at_zero),
        ])
        .expect("honest coefficients");
        for &coefficient in round.coefficients() {
            transcript.absorb_scalar(env, coefficient);
        }
        let challenge = transcript.challenge(env);
        challenges.push(challenge);

        for j in 0..half {
            let lo = table[j];
            let hi = table[j + half];
            table[j] = Bn254::add(lo, Bn254::mul(challenge, Bn254::sub(hi, lo)));
        }
        table.truncate(half);
        rounds.push(round);
    }

    (rounds, challenges)
}

struct Fixture {
    vk_bytes: Vec<u8>,
    proof_bytes: Vec<u8>,
    claimed_sum: u256,
    relation_evaluation: u256,
    evaluation_offset: usize,
    sumcheck_offset: usize,
}

fn make_fixture(env: &Env, hasher: ChallengeHash) -> Fixture {
    let vk = synthetic_vk(LOG_N, 0);
    let vk_bytes = vk.to_bytes();

    let commitments: Vec<G1Affine> = (1u64..=11).map(commitment_for_linear).collect();
    let generator = g1_generator();

    let mut proof = HonkProof {
        version: HONK_FORMAT_VERSION,
        wire_commitments: [
            commitments[0],
            commitments[1],
            commitments[2],
            commitments[3],
        ],
        grand_product_commitment: commitments[4],
        lookup_commitments: [commitments[5], commitments[6], commitments[7]],
        libra_commitments: [commitments[8], commitments[9], commitments[10]],
        sumcheck_univariates: [RoundPolynomial::<SUMCHECK_TERMS>::zero(); MAX_LOG_N as usize],
        num_rounds: LOG_N as usize,
        sumcheck_evaluations: [u256::from(0u8); NUM_SUMCHECK_EVALUATIONS],
        shplonk_q: generator,
        kzg_quotient: generator,
    };

    // Replay the verifier's absorb order up to the Sumcheck rounds.
    let mut transcript = HonkTranscript::new(
        env,
        hasher,
        &honk_vk_digest(&vk_bytes),
        &honk_public_inputs_digest(&[]),
    );
    for commitment in &proof.wire_commitments {
        transcript.absorb_point(env, commitment);
    }
    let _eta = transcript.challenge(env);
    transcript.absorb_point(env, &proof.grand_product_commitment);
    let _beta = transcript.challenge(env);
    let _gamma = transcript.challenge(env);
    for commitment in &proof.lookup_commitments {
        transcript.absorb_point(env, commitment);
    }
    for commitment in &proof.libra_commitments {
        transcript.absorb_point(env, commitment);
    }
    let _alpha = transcript.challenge(env);

    // p(0,0)=1, p(0,1)=2, p(1,0)=3, p(1,1)=4.
    let polynomial = MultilinearPolynomial::<4>::from_evaluations(&[
        u256::from(1u8),
        u256::from(2u8),
        u256::from(3u8),
        u256::from(4u8),
    ])
    .expect("valid polynomial");

    let (rounds, challenges) = honest_rounds(env, polynomial.evaluations(), &mut transcript);
    proof.sumcheck_univariates[..rounds.len()].copy_from_slice(&rounds);

    let zeta = *challenges.last().expect("at least one round");
    let zeta_inverse = Bn254::invert(zeta);

    // Every commitment is to f_i(X) = a_i + X, so its opening at ζ is a_i + ζ
    // and at ζ⁻¹ is a_i + ζ⁻¹, with opening proof 1 for both.
    for (index, evaluation) in proof.sumcheck_evaluations.iter_mut().enumerate() {
        *evaluation = if index < NUM_UNSHIFTED_EVALUATIONS {
            Bn254::add(u256::from(index as u64 + 1), zeta)
        } else {
            Bn254::add(
                u256::from((index - NUM_UNSHIFTED_EVALUATIONS) as u64 + 1),
                zeta_inverse,
            )
        };
    }

    Fixture {
        vk_bytes,
        proof_bytes: proof.to_bytes(),
        claimed_sum: polynomial.hypercube_sum(),
        relation_evaluation: polynomial.evaluate(&challenges).expect("valid point"),
        evaluation_offset: 4 + 11 * 64 + LOG_N as usize * SUMCHECK_TERMS * 32,
        sumcheck_offset: 4 + 11 * 64,
    }
}

fn flip_byte(bytes: &mut [u8], offset: usize) {
    bytes[offset] ^= 1;
}


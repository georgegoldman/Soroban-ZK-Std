#[test]
fn transcript_is_deterministic_and_hash_dependent() {
    let env = Env::default();

    let mut a = HonkTranscript::new(&env, ChallengeHash::Poseidon2, &[1u8; 32], &[2u8; 32]);
    let first = a.challenge(&env);
    let second = a.challenge(&env);
    assert_ne!(first, second, "consecutive challenges must differ");
    assert!(Bn254::is_valid_scalar(first));

    let mut b = HonkTranscript::new(&env, ChallengeHash::Poseidon2, &[1u8; 32], &[2u8; 32]);
    assert_eq!(b.challenge(&env), first);
    assert_eq!(b.challenge(&env), second);

    let mut keccak = HonkTranscript::new(&env, ChallengeHash::Keccak256, &[1u8; 32], &[2u8; 32]);
    let keccak_first = keccak.challenge(&env);
    assert!(Bn254::is_valid_scalar(keccak_first));
    assert_ne!(
        keccak_first, first,
        "hash choice must change the transcript"
    );
}

#[test]
fn challenges_bind_the_public_inputs() {
    let env = Env::default();
    let vk = synthetic_vk(LOG_N, 1);
    let vk_bytes = vk.to_bytes();
    let fixture = make_fixture(&env, ChallengeHash::Poseidon2);
    let proof = HonkProof::from_bytes(&fixture.proof_bytes, LOG_N).expect("valid proof");

    let with_one = derive_honk_challenges(
        &env,
        &vk,
        &proof,
        &[u256::from(1u8)],
        ChallengeHash::Poseidon2,
    )
    .expect("challenges");
    let with_two = derive_honk_challenges(
        &env,
        &vk,
        &proof,
        &[u256::from(2u8)],
        ChallengeHash::Poseidon2,
    )
    .expect("challenges");

    assert_ne!(with_one.nu, with_two.nu);
    assert_ne!(with_one.zeta(), with_two.zeta());
    assert_eq!(with_one.num_rounds, LOG_N as usize);
    assert_eq!(honk_vk_digest(&vk_bytes).len(), 32);
}

// ── KZG opening reduction ──────────────────────────────────────────────────

fn opening_claim(coeffs: &[ArkFr], point: u64, quotient: &[ArkFr]) -> OpeningClaim {
    let z = ArkFr::from(point);
    let mut evaluation = ArkFr::from(0u64);
    let mut power = ArkFr::from(1u64);
    for &coefficient in coeffs {
        evaluation += coefficient * power;
        power *= z;
    }
    OpeningClaim {
        commitment: commit(coeffs),
        point: field_to_u256(z),
        evaluation: field_to_u256(evaluation),
        proof: commit(quotient),
    }
}

#[test]
fn shplonk_accepts_a_genuine_kzg_opening() {
    let env = Env::default();
    env.cost_estimate().budget().reset_unlimited();

    // f(X) = 3 + 5X + 7X², opened at z = 5 with quotient 40 + 7X.
    let claim = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        5,
        &[ArkFr::from(40u64), ArkFr::from(7u64)],
    );

    let (q, r) = reduce_opening_claims(&[claim], u256::from(9u8)).expect("reduction");
    assert_ne!(q, G1_IDENTITY);
    assert_ne!(r, G1_IDENTITY);

    assert!(
        verify_kzg_openings(&env, &[claim], u256::from(9u8), srs_g2()).expect("pairing call"),
        "honest opening must satisfy the Shplonk equation"
    );
}

#[test]
fn shplonk_batches_distinct_points() {
    let env = Env::default();
    env.cost_estimate().budget().reset_unlimited();

    // f opened at z = 5 and at z = 3, each with its own quotient.
    let at_five = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        5,
        &[ArkFr::from(40u64), ArkFr::from(7u64)],
    );
    let at_three = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        3,
        &[ArkFr::from(26u64), ArkFr::from(7u64)],
    );

    assert!(
        verify_kzg_openings(&env, &[at_five, at_three], u256::from(11u8), srs_g2())
            .expect("pairing call")
    );
}

#[test]
fn shplonk_rejects_tampered_evaluations() {
    let env = Env::default();
    env.cost_estimate().budget().reset_unlimited();

    let mut claim = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        5,
        &[ArkFr::from(40u64), ArkFr::from(7u64)],
    );
    let genuine = claim.evaluation;
    claim.evaluation = Bn254::add(genuine, u256::from(1u8));
    assert!(
        !verify_kzg_openings(&env, &[claim], u256::from(9u8), srs_g2()).expect("pairing call"),
        "tampered evaluation must not verify"
    );

    let mut swapped = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        5,
        &[ArkFr::from(40u64), ArkFr::from(7u64)],
    );
    swapped.point = u256::from(6u8);
    assert!(
        !verify_kzg_openings(&env, &[swapped], u256::from(9u8), srs_g2()).expect("pairing call"),
        "wrong evaluation point must not verify"
    );
}

#[test]
fn shplonk_rejects_invalid_parameters() {
    let env = Env::default();
    let claim = opening_claim(
        &[ArkFr::from(3u64), ArkFr::from(5u64), ArkFr::from(7u64)],
        5,
        &[ArkFr::from(40u64), ArkFr::from(7u64)],
    );

    assert_eq!(
        reduce_opening_claims(&[], u256::from(1u8)),
        Err(ZkError::InvalidInput)
    );
    assert_eq!(
        reduce_opening_claims(&[claim], u256::from(0u8)),
        Err(ZkError::InvalidFieldElement)
    );
    assert_eq!(
        reduce_opening_claims(&[claim], Bn254::FR_MODULUS),
        Err(ZkError::InvalidFieldElement)
    );
    assert_eq!(
        verify_kzg_openings(
            &env,
            &[claim],
            u256::from(1u8),
            G2Affine {
                x: (u256::from(0u8), u256::from(0u8)),
                y: (u256::from(0u8), u256::from(0u8))
            }
        ),
        Err(ZkError::InvalidInput)
    );
}


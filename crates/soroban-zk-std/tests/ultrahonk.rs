#[test]
fn verifying_key_rejects_malformed_bytes() {
    let vk = synthetic_vk(4, 1);
    let bytes = vk.to_bytes();

    // Truncated.
    assert_eq!(
        HonkVerifyingKey::from_bytes(&bytes[..bytes.len() - 1]),
        Err(ZkError::DeserializationError)
    );
    // Wrong version.
    let mut wrong_version = bytes.clone();
    wrong_version[..4].copy_from_slice(&2u32.to_be_bytes());
    assert_eq!(
        HonkVerifyingKey::from_bytes(&wrong_version),
        Err(ZkError::DeserializationError)
    );
    // Zero log_n.
    let mut zero_log = bytes.clone();
    zero_log[4..8].copy_from_slice(&0u32.to_be_bytes());
    assert_eq!(
        HonkVerifyingKey::from_bytes(&zero_log),
        Err(ZkError::InvalidInput)
    );
    // Off-curve selector commitment.
    let mut off_curve = bytes.clone();
    off_curve[12..44].copy_from_slice(&u256::from(1u8).to_be_bytes());
    off_curve[44..76].copy_from_slice(&u256::from(1u8).to_be_bytes());
    assert_eq!(
        HonkVerifyingKey::from_bytes(&off_curve),
        Err(ZkError::DeserializationError)
    );
    // Invalid SRS G2 point.
    let mut zero_srs = bytes;
    let srs_offset = HonkVerifyingKey::BYTE_LEN - 128;
    zero_srs[srs_offset..].fill(0);
    assert_eq!(
        HonkVerifyingKey::from_bytes(&zero_srs),
        Err(ZkError::DeserializationError)
    );
}

#[test]
fn proof_rejects_malformed_bytes() {
    let env = Env::default();
    let fixture = make_fixture(&env, ChallengeHash::Poseidon2);

    // Wrong length for the declared circuit size.
    assert_eq!(
        HonkProof::from_bytes(&fixture.proof_bytes, LOG_N + 1),
        Err(ZkError::DeserializationError)
    );
    // Trailing byte.
    let mut long = fixture.proof_bytes.clone();
    long.push(0);
    assert_eq!(
        HonkProof::from_bytes(&long, LOG_N),
        Err(ZkError::DeserializationError)
    );
    // Out-of-range evaluation (0xff.. > Fr modulus).
    let mut bad_scalar = fixture.proof_bytes.clone();
    bad_scalar[fixture.evaluation_offset..fixture.evaluation_offset + 32].fill(0xff);
    assert_eq!(
        HonkProof::from_bytes(&bad_scalar, LOG_N),
        Err(ZkError::InvalidFieldElement)
    );
    // Off-curve wire commitment.
    let mut off_curve = fixture.proof_bytes;
    off_curve[4..36].copy_from_slice(&u256::from(5u8).to_be_bytes());
    off_curve[36..68].copy_from_slice(&u256::from(7u8).to_be_bytes());
    assert_eq!(
        HonkProof::from_bytes(&off_curve, LOG_N),
        Err(ZkError::DeserializationError)
    );
}

#[test]
fn identity_commitment_encoding_is_accepted() {
    let env = Env::default();
    let mut fixture = make_fixture(&env, ChallengeHash::Poseidon2);
    // Zero out the first wire commitment: Barretenberg's identity encoding.
    fixture.proof_bytes[4..68].fill(0);
    let proof = HonkProof::from_bytes(&fixture.proof_bytes, LOG_N).expect("identity is valid");
    assert_eq!(proof.wire_commitments[0], G1_IDENTITY);
}


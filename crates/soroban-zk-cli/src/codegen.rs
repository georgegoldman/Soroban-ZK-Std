//! Rust source generation for `import-vk`.
//!
//! The output is `no_std`-compatible and allocation-free: every value is a
//! `const` built with `ethnum::u256::from_words`, the IC points are a
//! fixed-size `const` array, and the verifying key borrows it as
//! `&'static [G1Affine]`. It needs the `ethnum`, `soroban-zk-core` and
//! `soroban-zk-std` crates, which every contract using `groth16_verify`
//! already depends on.

use core::fmt::Write as _;

use crate::bn254::{G1, G2};
use crate::formats::{VerifyingKey, VkFormat};

/// Checks that `name` is a valid upper-case Rust constant identifier.
pub fn validate_const_name(name: &str) -> Result<(), String> {
    let mut chars = name.chars();
    let ok = matches!(chars.next(), Some(c) if c.is_ascii_uppercase() || c == '_')
        && name
            .chars()
            .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_');
    if ok {
        Ok(())
    } else {
        Err(format!(
            "--name `{name}` must be an UPPER_SNAKE_CASE Rust identifier"
        ))
    }
}

fn u256_lit(be: &[u8; 32], indent: &str) -> String {
    let mut hi = [0u8; 16];
    let mut lo = [0u8; 16];
    hi.copy_from_slice(&be[..16]);
    lo.copy_from_slice(&be[16..]);
    format!(
        "::ethnum::u256::from_words(\n{indent}    0x{:032x}_u128,\n{indent}    0x{:032x}_u128,\n{indent})",
        u128::from_be_bytes(hi),
        u128::from_be_bytes(lo)
    )
}

fn g1_lit(p: &G1, indent: &str) -> String {
    let inner = format!("{indent}    ");
    format!(
        "::soroban_zk_core::G1Affine {{\n{inner}x: {},\n{inner}y: {},\n{indent}}}",
        u256_lit(&p.x, &inner),
        u256_lit(&p.y, &inner)
    )
}

fn g2_lit(p: &G2, indent: &str) -> String {
    let i1 = format!("{indent}    ");
    let i2 = format!("{indent}        ");
    format!(
        "::soroban_zk_std::pairing::G2Affine {{\n\
         {i1}// (c0, c1) = (real, imaginary)\n\
         {i1}x: (\n{i2}{},\n{i2}{},\n{i1}),\n\
         {i1}y: (\n{i2}{},\n{i2}{},\n{i1}),\n\
         {indent}}}",
        u256_lit(&p.x.0, &i2),
        u256_lit(&p.x.1, &i2),
        u256_lit(&p.y.0, &i2),
        u256_lit(&p.y.1, &i2)
    )
}

/// Renders the verifying key as a Rust module body.
pub fn render_vk(vk: &VerifyingKey, format: VkFormat, name: &str) -> String {
    let n_ic = vk.ic.len();
    let mut s = String::new();
    let _ = writeln!(
        s,
        "// @generated by `soroban-zk import-vk --format {}`. Do not edit by hand.",
        format.name()
    );
    s.push_str(
        "//\n\
         // Groth16 verifying key over BN254, as `no_std`, allocation-free constants.\n\
         // All coordinates are canonical big-endian field elements, checked on the\n\
         // curve (and G2 in the prime-order subgroup) when this file was generated.\n\
         // G2 coordinates use the `soroban_zk_std::G2Affine` tuple order (c0, c1) =\n\
         // (real, imaginary); the EIP-197 `c1 || c0` byte order is applied by the\n\
         // library when the points are serialized.\n\
         //\n\
         // Requires the `ethnum`, `soroban-zk-core` and `soroban-zk-std` crates.\n\n",
    );
    let _ = writeln!(s, "/// Number of public inputs the circuit expects.");
    let _ = writeln!(
        s,
        "pub const {name}_NUM_PUBLIC_INPUTS: usize = {};\n",
        n_ic - 1
    );
    let _ = writeln!(
        s,
        "/// IC points: `acc = IC[0] + sum(public_input[i] * IC[i + 1])`."
    );
    let _ = writeln!(
        s,
        "pub const {name}_IC: [::soroban_zk_core::G1Affine; {n_ic}] = ["
    );
    for p in &vk.ic {
        let _ = writeln!(s, "    {},", g1_lit(p, "    "));
    }
    s.push_str("];\n\n");
    let _ = writeln!(s, "/// The Groth16 verifying key.");
    let _ = writeln!(
        s,
        "pub const {name}: ::soroban_zk_std::groth16::Groth16VerifyingKey<'static> =\n    \
         ::soroban_zk_std::groth16::Groth16VerifyingKey {{"
    );
    let ind = "        ";
    let _ = writeln!(s, "{ind}alpha_g1: {},", g1_lit(&vk.alpha_g1, ind));
    let _ = writeln!(s, "{ind}beta_g2: {},", g2_lit(&vk.beta_g2, ind));
    let _ = writeln!(s, "{ind}gamma_g2: {},", g2_lit(&vk.gamma_g2, ind));
    let _ = writeln!(s, "{ind}delta_g2: {},", g2_lit(&vk.delta_g2, ind));
    let _ = writeln!(s, "{ind}ic: &{name}_IC,");
    s.push_str("    };\n");
    s
}
